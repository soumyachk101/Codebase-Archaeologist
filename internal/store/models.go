package store

import "time"

// models.go defines the persisted entities, mirroring the data model in the
// spec. The relational graph is the durable source of truth; JSON-in-TEXT
// columns carry flexible fact sets without premature schema churn.
//
// Dialect note: every column is TEXT or INTEGER in both SQLite and
// PostgreSQL. Dates are RFC3339 strings, booleans are 0/1, and JSON
// payloads are TEXT. This keeps one code path for both drivers; the
// production migration in infrastructure/ proves compatibility, and a
// follow-up can move JSON payloads to JSONB without changing the API.

// Repository is an indexed codebase.
type Repository struct {
	ID        string    `json:"id"`
	Name      string    `json:"name"`
	Origin    string    `json:"origin"` // "local" | "github"
	Root      string    `json:"root"`   // local path when origin=local
	CreatedAt time.Time `json:"createdAt"`
}

// IndexRun is one commit-aware snapshot of a repository. A run is current
// for its repository when it is the newest "complete" run. All facts are
// stamped with the run's commit, so stale runs are invisible to readers.
type IndexRun struct {
	ID           string     `json:"id"`
	RepositoryID string     `json:"repositoryId"`
	Commit       string     `json:"commit"`
	CommitDate   time.Time  `json:"commitDate"`
	Branch       string     `json:"branch"`
	ParserVersion string    `json:"parserVersion"`
	Status       string     `json:"status"` // pending|indexing|complete|failed
	IndexedAt    *time.Time `json:"indexedAt,omitempty"`
	IndexedFiles int        `json:"indexedFiles"`
	IndexerVersion string  `json:"indexerVersion"`
	ErrorMessage string     `json:"errorMessage,omitempty"`
	// ParentCommit is the previous run's commit when this run is
	// incremental; empty for full index runs.
	ParentCommit string `json:"parentCommit,omitempty"`
}

// File is a source file in an index run.
type File struct {
	ID           string   `json:"id"`
	Commit       string   `json:"commit"`
	Path         string   `json:"path"`
	Language     string   `json:"language"`
	Module       string   `json:"module"`
	Checksum     string   `json:"checksum"`
	SizeBytes    int64    `json:"sizeBytes"`
	Exports      []string `json:"exports"`
	TopSymbols   int      `json:"topSymbols"`
	FirstCommit  string   `json:"firstCommit"`
	LastCommit   string   `json:"lastCommit"`
}

// Symbol is one declaration with full provenance.
type Symbol struct {
	ID            string    `json:"id"`
	Commit        string    `json:"commit"`
	File          string    `json:"file"`
	Kind          string    `json:"kind"`
	Name          string    `json:"name"`
	QualifiedName string    `json:"qualifiedName"`
	Language      string    `json:"language"`
	StartLine     int32     `json:"startLine"`
	EndLine       int32     `json:"endLine"`
	StartByte     int32     `json:"startByte"`
	EndByte       int32     `json:"endByte"`
	Exported      bool      `json:"exported"`
	IsTest        bool      `json:"isTest"`
	Parent        string    `json:"parent,omitempty"`
	Key           string    `json:"key"`
	Module        string    `json:"module"`
}

// EdgeKind classifies a graph edge.
type EdgeKind string

// Edge is a persisted relationship. Static edges point at a concrete
// symbol; co-change edges link a file to a commit instead of to another
// symbol and are displayed distinctly in the UI.
type Edge struct {
	ID          string   `json:"id"`
	Commit      string   `json:"commit"`
	FromID      string   `json:"fromId"`
	ToID        string   `json:"toId"`
	Kind        EdgeKind `json:"kind"`
	Resolved    bool     `json:"resolved"`
	Confidence  string   `json:"confidence"` // "static" | "unresolved" | "historical"
	TargetHint  string   `json:"targetHint"`
	SourceFile  string   `json:"sourceFile"`
	SourceLine  int32    `json:"sourceLine"`
}

// CoChange is historical co-change evidence, distinct from static edges.
type CoChange struct {
	FileA      string    `json:"fileA"`
	FileB      string    `json:"fileB"`
	Commit     string    `json:"commit"`
	CommitDate time.Time `json:"commitDate"`
	Count      int       `json:"count"`
}

// EvidenceRef is one cited piece of indexed evidence for an answer.
type EvidenceRef struct {
	File    string `json:"file"`
	Line    int32  `json:"line"`
	EndLine int32  `json:"endLine,omitempty"`
	Symbol  string `json:"symbol,omitempty"`
	Commit  string `json:"commit"`
	Snippet string `json:"snippet,omitempty"`
	Note    string `json:"note,omitempty"`
}

// Answer is a stored explanation with its evidence set. Mode "ai" means
// the text was generated by a configured model and MUST be displayed as
// derived; the evidence list is what is verified.
type Answer struct {
	ID         string        `json:"id"`
	Commit     string        `json:"commit"`
	Question   string        `json:"question"`
	Answer     string        `json:"answer"`
	Mode       string        `json:"mode"` // "grounded" | "ai" | "abstain"
	Confidence string        `json:"confidence"` // "high" | "medium" | "low"
	Derived    bool          `json:"derived"`
	CreatedAt  time.Time     `json:"createdAt"`
	Evidence   []EvidenceRef `json:"evidence"`
}

// schemaDDL returns the CREATE TABLE / CREATE INDEX statements. Both
// dialects share the column types; only the DDL is dialect-specific.
func schemaDDL(driver Driver) []string {
	if driver == SQLite {
		return sqliteDDL
	}
	return postgresDDL
}

var sqliteDDL = []string{
	`CREATE TABLE IF NOT EXISTS repositories (
		id TEXT PRIMARY KEY,
		name TEXT NOT NULL,
		origin TEXT NOT NULL DEFAULT 'local',
		root TEXT NOT NULL DEFAULT '',
		created_at TEXT NOT NULL
	)`,
	`CREATE TABLE IF NOT EXISTS index_runs (
		id TEXT PRIMARY KEY,
		repository_id TEXT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
		commit TEXT NOT NULL,
		commit_date TEXT NOT NULL,
		branch TEXT NOT NULL DEFAULT '',
		parser_version TEXT NOT NULL DEFAULT '',
		status TEXT NOT NULL DEFAULT 'pending',
		indexed_at TEXT,
		indexed_files INTEGER NOT NULL DEFAULT 0,
		indexer_version TEXT NOT NULL DEFAULT '',
		error_message TEXT NOT NULL DEFAULT '',
		parent_commit TEXT NOT NULL DEFAULT ''
	)`,
	`CREATE INDEX IF NOT EXISTS idx_runs_repo ON index_runs(repository_id)`,
	`CREATE TABLE IF NOT EXISTS files (
		id TEXT NOT NULL,
		commit TEXT NOT NULL,
		path TEXT NOT NULL,
		language TEXT NOT NULL DEFAULT '',
		module TEXT NOT NULL DEFAULT '',
		checksum TEXT NOT NULL DEFAULT '',
		size_bytes INTEGER NOT NULL DEFAULT 0,
		exports TEXT NOT NULL DEFAULT '[]',
		top_symbols INTEGER NOT NULL DEFAULT 0,
		first_commit TEXT NOT NULL DEFAULT '',
		last_commit TEXT NOT NULL DEFAULT '',
		PRIMARY KEY (id, commit)
	)`,
	`CREATE INDEX IF NOT EXISTS idx_files_commit_path ON files(commit, path)`,
	`CREATE INDEX IF NOT EXISTS idx_files_module ON files(module)`,
	`CREATE TABLE IF NOT EXISTS symbols (
		id TEXT NOT NULL,
		commit TEXT NOT NULL,
		file TEXT NOT NULL,
		kind TEXT NOT NULL,
		name TEXT NOT NULL,
		qualified_name TEXT NOT NULL,
		language TEXT NOT NULL,
		start_line INTEGER NOT NULL,
		end_line INTEGER NOT NULL,
		start_byte INTEGER NOT NULL DEFAULT 0,
		end_byte INTEGER NOT NULL DEFAULT 0,
		exported INTEGER NOT NULL DEFAULT 0,
		is_test INTEGER NOT NULL DEFAULT 0,
		parent TEXT NOT NULL DEFAULT '',
		module TEXT NOT NULL DEFAULT '',
		PRIMARY KEY (id, commit)
	)`,
	`CREATE INDEX IF NOT EXISTS idx_symbols_commit_file ON symbols(commit, file)`,
	`CREATE INDEX IF NOT EXISTS idx_symbols_commit_name ON symbols(commit, name)`,
	`CREATE INDEX IF NOT EXISTS idx_symbols_commit_kind ON symbols(commit, kind)`,
	`CREATE TABLE IF NOT EXISTS symbol_versions (
		symbol_id TEXT NOT NULL,
		key TEXT NOT NULL,
		commit TEXT NOT NULL,
		start_line INTEGER NOT NULL,
		end_line INTEGER NOT NULL,
		changed INTEGER NOT NULL DEFAULT 0,
		PRIMARY KEY (symbol_id, commit)
	)`,
	`CREATE INDEX IF NOT EXISTS idx_symver_key ON symbol_versions(key)`,
	`CREATE TABLE IF NOT EXISTS edges (
		id TEXT NOT NULL,
		commit TEXT NOT NULL,
		from_id TEXT NOT NULL,
		to_id TEXT NOT NULL DEFAULT '',
		kind TEXT NOT NULL,
		resolved INTEGER NOT NULL DEFAULT 0,
		confidence TEXT NOT NULL DEFAULT 'unresolved',
		target_hint TEXT NOT NULL DEFAULT '',
		source_file TEXT NOT NULL,
		source_line INTEGER NOT NULL DEFAULT 0,
		PRIMARY KEY (id, commit)
	)`,
	`CREATE INDEX IF NOT EXISTS idx_edges_commit_from ON edges(commit, from_id)`,
	`CREATE INDEX IF NOT EXISTS idx_edges_commit_to ON edges(commit, to_id)`,
	`CREATE INDEX IF NOT EXISTS idx_edges_commit_kind ON edges(commit, kind)`,
	`CREATE TABLE IF NOT EXISTS co_changes (
		file_a TEXT NOT NULL,
		file_b TEXT NOT NULL,
		commit TEXT NOT NULL,
		commit_date TEXT NOT NULL,
		count INTEGER NOT NULL DEFAULT 0,
		PRIMARY KEY (file_a, file_b, commit)
	)`,
	`CREATE INDEX IF NOT EXISTS idx_cochange_files ON co_changes(file_a, file_b)`,
	`CREATE TABLE IF NOT EXISTS commits (
		commit TEXT PRIMARY KEY,
		branch TEXT NOT NULL DEFAULT '',
		message TEXT NOT NULL DEFAULT '',
		author TEXT NOT NULL DEFAULT '',
		date TEXT NOT NULL,
		files TEXT NOT NULL
	)`,
	`CREATE TABLE IF NOT EXISTS answers (
		id TEXT PRIMARY KEY,
		commit TEXT NOT NULL,
		question TEXT NOT NULL,
		answer TEXT NOT NULL,
		mode TEXT NOT NULL,
		confidence TEXT NOT NULL,
		derived INTEGER NOT NULL DEFAULT 0,
		created_at TEXT NOT NULL,
		evidence TEXT NOT NULL DEFAULT '[]'
	)`,
}

